'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn, execFileSync } = require('node:child_process');
const { once } = require('node:events');
const { NativeSessionClient } = require('../dist/services/native-client.js');
const { SessionRouter } = require('../dist/services/session-router.js');
const { LocalServiceHost } = require('../dist/services/local-endpoint.js');
const { encodeRequest, decodeReply } = require('../dist/services/contracts.js');
const { StdioPeer } = require('./stdio-peer.cjs');
const host = process.env.ARES_HOST || path.resolve(__dirname, '../../build-electron-make/bin/ares-electron-host');
const fixture = process.env.ARES_CPU_FIXTURE || path.join(path.dirname(host), 'ares-electron-cpu-fixture');
const identity = { session: 'machine-live', epoch: 1 }, empty = { gpr: [], pc: null, hi: null, lo: null, status: null, llbit: null };
const unwrap = r => { assert.equal(r.ok, true, JSON.stringify(r)); return r.result; };
const sleep = ms => new Promise(r => setTimeout(r, ms));
test('real N64 inspection: guest-order full/range dumps, stack heuristics and render deltas', { timeout: 30000 }, async () => {
  const dir = fs.mkdtempSync('/tmp/ares-inspection-live-'), image = Buffer.alloc(0x1000);
  image.writeUInt32BE(0x80371240); image.write('MACHINE FIXTURE', 0x20); image[0x3e] = 0x45;
  image.writeUInt32BE(0x24020007, 0x80); image.writeUInt32BE(0x1000ffff, 0x84); image.writeUInt32BE(0, 0x88);
  const rom = path.join(dir, 'fixture.z64'), settings = path.join(dir, 'settings.bml'); fs.writeFileSync(rom, image); fs.writeFileSync(settings, '');
  const child = spawn(host, ['--rom', rom, '--system', 'Nintendo 64', '--settings', settings, '--silent', '--paused', '--save-dir', path.join(dir, 'saves'), '--control-session', identity.session], { stdio: ['pipe', 'pipe', 'pipe', 'pipe'] });
  const closed = once(child, 'close'); let log = ''; child.stderr.on('data', b => log = (log + b).slice(-20000)); child.stdout.resume();
  const native = new NativeSessionClient(child.stdin, child.stdio[3], identity, () => {}), router = new SessionRouter(); router.attach(native);
  const endpoint = new LocalServiceHost(router); let peer;
  try {
    unwrap(await native.request('session.status')); await endpoint.listen(path.join(dir, 'ipc'));
    peer = new StdioPeer(process.execPath, [path.resolve(__dirname, '../dist/mcp/server.js'), '--connection', endpoint.metadataFile, '--instance', endpoint.instance]); await peer.initialize();
    const rawFile = path.join(dir, 'raw.bs');
    assert.equal((await peer.tool('state_save', { path: rawFile })).error, undefined);
    const layout = unwrap(await native.request('n64.state.layout')), initialized = fs.readFileSync(rawFile);
    initialized[layout.offset + layout.size] = 1; // original fixture's RDRAM map
    const initializedFile = path.join(dir, 'initialized.bs'); fs.writeFileSync(initializedFile, initialized);
    assert.equal((await peer.tool('state_load', { path: initializedFile })).error, undefined);
    const pattern = Buffer.from(Array.from({ length: 1024 }, (_, i) => i & 255));
    assert.equal((await peer.tool('write_memory_va', { addr: '0x1000', hex_bytes: pattern.toString('hex'), view: 'rdram' })).written, 1024);
    const before = await peer.tool('cpu_registers', { cop0: true });
    const rangePath = path.join(dir, 'range.bin');
    const range = await peer.tool('dump_range', { addr: '0x80001003', length: 1000, path: rangePath });
    assert.equal(range.error, undefined, JSON.stringify(range)); assert.equal(range.length, 1000); assert.equal(range.paddr, '0x1003');
    assert.deepEqual(fs.readFileSync(rangePath), pattern.subarray(3, 1003));
    assert.equal((await peer.tool('dump_range', { addr: '0xa0001003', length: 1000, path: rangePath })).error, 'file_exists');
    assert.equal((await peer.tool('dump_range', { addr: '0x7fffff', length: 2, path: path.join(dir, 'bad') })).error, 'out_of_bounds');
    const fullPath = path.join(dir, 'full.bin');
    assert.equal((await peer.tool('dump_rdram', { path: fullPath, expect_size: 1 })).error, 'size_mismatch'); assert.equal(fs.existsSync(fullPath), false);
    const full = await peer.tool('dump_rdram', { path: fullPath, expect_size: layout.size });
    assert.equal(full.error, undefined, JSON.stringify(full)); assert.equal(full.size, layout.size);
    const bytes = fs.readFileSync(fullPath); assert.equal(bytes.length, layout.size); assert.deepEqual(bytes.subarray(0x1000, 0x1400), pattern);
    assert.equal(full.sha256, require('node:crypto').createHash('sha256').update(bytes).digest('hex'));
    assert.deepEqual(await peer.tool('cpu_registers', { cop0: true }), before, 'dumps never advance CPU');
    assert.equal((await peer.tool('emu_status')).paused, true);
    const probe = await peer.tool('render_probe'); assert.equal(probe.originChanged, null); assert.ok(Number.isFinite(probe.vps)); assert.ok(Number.isSafeInteger(probe.presented_frame));
    const again = await peer.tool('render_probe'); assert.equal(again.originChanged, false); assert.equal(again.dpcAdvanced, false); assert.equal(again.frameAdvanced, false);
    const cpuProgram = Buffer.alloc(16); [0x27bdffe0, 0xffbf0018, 0, 0].forEach((w, i) => cpuProgram.writeUInt32BE(w, i * 4));
    await peer.tool('write_memory_va', { addr: '0x30000', hex_bytes: cpuProgram.toString('hex'), view: 'rdram' });
    await peer.tool('write_memory_va', { addr: '0x30100', hex_bytes: '0c00c0000000000000000000', view: 'rdram' });
    await peer.tool('write_memory_va', { addr: '0x31018', hex_bytes: 'ffffffff80030108', view: 'rdram' });
    await peer.tool('cpu_set_registers', { pc: '0x80030008', gpr: { sp: '0xffffffff80031000', ra: '0xffffffff80030108' } });
    const stack = await peer.tool('stack', { function_start: '0x80030000' });
    assert.equal(stack.error, undefined, JSON.stringify(stack)); assert.equal(stack.heuristic, true); assert.equal(stack.frames[0].return_address, '0xffffffff80030108'); assert.equal(stack.frames[0].frame_size, 32); assert.equal(stack.frames[0].confidence, 'high');
    assert.equal((await peer.tool('stack', { function_start: '0x80030001' })).error, 'invalid_function_start');
    const run = unwrap(await native.request('execution.runFrames', undefined, { count: 1, timeoutMs: 1000 }));
    assert.equal((await peer.tool('dump_range', { addr: 0, length: 1, path: fullPath })).error, 'busy');
    assert.equal((await peer.tool('render_probe')).epoch, native.identity.epoch);
    unwrap(await native.request('execution.cancel', undefined, { operationId: run.operation_id }));
    await peer.tool('resume');
    const runningDump = await peer.tool('dump_range', { addr: '0x1000', length: 16, path: path.join(dir, 'running.bin') });
    assert.equal(runningDump.error, undefined, JSON.stringify(runningDump));
    assert.equal(runningDump.stopped, false); assert.equal((await peer.tool('emu_status')).paused, false, 'snapshot preserves ordinary play');
    await peer.tool('pause');
    await peer.close(); peer = undefined; await endpoint.close(); router.detach(); native.close(); child.stdin.end('quit\n'); assert.equal((await closed)[0], 0, log);
  } finally {
    if (peer) await peer.close(); await endpoint.close(); router.detach(); native.close(); if (child.exitCode === null) { child.kill('SIGKILL'); await closed; } fs.rmSync(dir, { recursive: true, force: true });
  }
});
