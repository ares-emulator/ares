import { app, BrowserWindow, Menu } from 'electron';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { makeFixture } from '../fixture.cjs';
const temporary = fs.mkdtempSync('/tmp/ares-workspace-ui-'), profile = path.join(temporary, 'profile'), source = path.join(temporary, 'plugin');
fs.mkdirSync(source); fs.mkdirSync(profile);
const rom = path.join(temporary, 'fixture.gb'); fs.writeFileSync(rom, makeFixture());
fs.writeFileSync(path.join(source, 'manifest.json'), JSON.stringify({ id: 'test.workspace', name: 'Workspace fixture', version: '1.0.0', apiVersion: 1, entry: 'plugin.js', capabilities: [], contributes: { panels: [{ id: 'counter', title: 'Counter' }], commands: [{ id: 'open', title: 'Open counter' }] } }));
fs.writeFileSync(path.join(source, 'plugin.js'), `export function activate(ctx) {
  ctx.ui.registerPanel('counter', ({element, signal, onVisibility}) => {
    window.panelMounts = (window.panelMounts || 0) + 1;
    element.innerHTML = '<h2>Workspace panel</h2><button>Action</button>';
    ctx.scope.listen(element, 'pointerdown', () => {});
    ctx.scope.interval(() => { element.dataset.ticks = String(Number(element.dataset.ticks || 0) + 1); }, 50);
    onVisibility(visible => { element.dataset.visible = String(visible); });
    return () => { if (!signal.aborted) throw new Error('instance was not aborted'); window.panelCleanups = (window.panelCleanups || 0) + 1; };
  });
  ctx.ui.registerCommand('open', () => ctx.ui.openPanel('counter'));
}`);
app.setPath('userData', profile);
Object.assign(process.env, { ARES_PROFILE_DIR: profile, ARES_PLUGIN_DIRS: source, ARES_ROM: rom, ARES_AUTOTEST: '', ARES_SILENT: '1', ARES_BACKGROUND_TEST: '1', ARES_DEFAULT_PLUGINS: '0', ARES_ENABLE_SERVICES: '0' });
delete process.env.ARES_DISABLE_PLUGINS; delete process.env.ARES_SETTINGS;
const { plugins, sessions } = await import('../dist/main.js');
const until = async check => { for (let i = 0; i < 300; i++) { try { const result = await check(); if (result) return result; } catch {} await new Promise(resolve => setTimeout(resolve, 20)); } throw new Error('workspace check timed out'); };
const deadline = setTimeout(() => app.exit(1), 30000);
app.on('will-quit', () => { clearTimeout(deadline); fs.rmSync(temporary, { recursive: true, force: true }); });
app.whenReady().then(async () => {
  try {
    const window = await until(() => BrowserWindow.getAllWindows()[0]);
    const js = code => window.webContents.executeJavaScript(code);
    await until(() => js("typeof window.stats === 'function' && !!document.querySelector('[data-plugin-command]')"));
    assert.equal(await js("!!document.querySelector('body > header, body > nav, body > aside, #metrics, #stress, #synthetic')"), false);
    assert.equal(await js("document.querySelector('#settings-dialog').open"), false);
    assert.equal(await js("getComputedStyle(document.querySelector('.area-toolbar')).display"), 'none');
    const identity = await sessions.request('session.status');
    const menu = Menu.getApplicationMenu().items.flatMap(item => item.submenu?.items ?? []);
    const settings = menu.find(item => item.label === 'Settings…'); assert.equal(settings.accelerator, 'CmdOrCtrl+,'); settings.click();
    await until(() => js("document.querySelector('#settings-dialog').open"));
    fs.mkdirSync(path.resolve('artifacts'), { recursive: true });
    await new Promise(resolve => setTimeout(resolve, 200));
    fs.writeFileSync(path.resolve('artifacts/settings-window.png'), (await window.webContents.capturePage()).toPNG());
    await js("document.querySelector('#close-settings').click()");
    await js("window.dispatchEvent(new KeyboardEvent('keydown', {code:'KeyL', metaKey:true, shiftKey:true, bubbles:true, cancelable:true}))");
    assert.equal(await js("document.querySelector('#workspace').classList.contains('editing')"), true);
    await js("document.querySelector('[aria-label=\"Split side by side\"]').click()");
    await until(() => js("document.querySelectorAll('.workspace-area').length === 2"));
    await js("(()=>{const select = [...document.querySelectorAll('.area-toolbar select')].at(-1); select.value='plugin:test.workspace:counter'; select.dispatchEvent(new Event('change'));})()");
    await until(() => js("document.querySelector('[data-plugin-panel]')?.dataset.ticks > 0"));
    assert.equal(await js("window.panelMounts"), 1);
    // Drive actual browser pointer events through the divider and floating window.
    const divider = await js("(()=>{const r=document.querySelector('.split-divider').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()");
    const drag = async (from, dx, dy) => {
      window.webContents.sendInputEvent({ type:'mouseDown', button:'left', x:Math.round(from.x), y:Math.round(from.y), clickCount:1 });
      window.webContents.sendInputEvent({ type:'mouseMove', x:Math.round(from.x+dx), y:Math.round(from.y+dy) });
      window.webContents.sendInputEvent({ type:'mouseUp', button:'left', x:Math.round(from.x+dx), y:Math.round(from.y+dy), clickCount:1 });
      await new Promise(resolve => setTimeout(resolve, 80));
    };
    await drag(divider, 80, 0);
    await until(() => JSON.parse(fs.readFileSync(path.join(profile, 'workspace.json'))).root.ratio > 0.55);
    const panel = 'plugin:test.workspace:counter';
    // Add a second, independently mounted instance as a popup through Settings.
    settings.click();
    await js("document.querySelector('[data-tab=workspace]').click()");
    await js(`(()=>{document.querySelector('#floating-panel').value=${JSON.stringify(panel)};document.querySelector('#add-floating').click();})()`);
    await until(() => js("document.querySelectorAll('[data-plugin-panel]').length === 2"));
    assert.equal(await js('window.panelMounts'), 2);
    await js("document.querySelector('#close-settings').click()");
    const header = await js("(()=>{const r=document.querySelector('.floating-header').getBoundingClientRect();return {x:r.x+30,y:r.y+r.height/2}})()");
    await drag(header, 90, 35);
    await until(() => JSON.parse(fs.readFileSync(path.join(profile, 'workspace.json'))).floating[0].x >= 140);
    const corner = await js("(()=>{const r=document.querySelector('.window-resize').getBoundingClientRect();return {x:r.x+8,y:r.y+8}})()");
    await drag(corner, 50, 30);
    await until(() => JSON.parse(fs.readFileSync(path.join(profile, 'workspace.json'))).floating[0].width >= 420);
    await js("void (window.hiddenPanel = document.querySelector('[data-floating] [data-plugin-panel]'))");
    await js("window.dispatchEvent(new KeyboardEvent('keydown', {code:'Digit1',metaKey:true,shiftKey:true,bubbles:true,cancelable:true}))");
    await until(() => js("!document.querySelector('[data-floating]')"));
    const hiddenTicks = await js('window.hiddenPanel.dataset.ticks');
    await new Promise(resolve => setTimeout(resolve, 150));
    assert.equal(await js('window.hiddenPanel.dataset.ticks'), hiddenTicks, 'hidden popup stops polling');
    await js("window.dispatchEvent(new KeyboardEvent('keydown', {code:'Digit1',metaKey:true,shiftKey:true,bubbles:true,cancelable:true}))");
    await until(() => js("!!document.querySelector('[data-floating]')"));
    assert.equal(await js('window.panelMounts'), 2, 'hotkey toggles retain instance state');
    settings.click(); await js("document.querySelector('[data-tab=workspace]').click()");
    await js("(()=>{const card=document.querySelector('.floating-card'),mode=card.querySelector('select');mode.value='overlay';mode.dispatchEvent(new Event('change'));})()");
    await js("(()=>{const input=document.querySelector('.floating-card input[type=checkbox]');input.checked=false;input.dispatchEvent(new Event('change'));})()");
    await js("document.querySelector('#close-settings').click()");
    // Finish layout editing before checking mouse passthrough.
    await js("window.dispatchEvent(new KeyboardEvent('keydown', {code:'KeyL',metaKey:true,shiftKey:true,bubbles:true,cancelable:true}))");
    assert.equal(await js("getComputedStyle(document.querySelector('.overlay')).pointerEvents"), 'none');
    assert.equal(await js('window.panelMounts'), 2, 'presentation changes never remount panel instances');
    settings.click(); await js("document.querySelector('[data-tab=workspace]').click()");
    await js("(()=>{const mode=document.querySelector('.floating-card select');mode.value='popup';mode.dispatchEvent(new Event('change'));})()");
    await js("document.querySelector('#close-settings').click()");
    const file = path.join(profile, 'workspace.json'); await until(() => fs.existsSync(file));
    await until(() => JSON.parse(fs.readFileSync(file)).floating[0].open === true);
    const saved = JSON.parse(fs.readFileSync(file));
    assert.equal(saved.root.axis, 'x'); assert.equal(saved.floating[0].shortcut, 'Mod+Shift+Digit1');
    await plugins.reload('test.workspace');
    await until(() => js("window.panelCleanups >= 2 && document.querySelectorAll('[data-plugin-panel]').length === 2"));
    const reloaded = await sessions.request('session.status'); assert.equal(reloaded.session, identity.session); assert.equal(reloaded.epoch, identity.epoch);
    await plugins.enable('test.workspace', false);
    await until(() => js("document.querySelectorAll('[data-plugin-panel]').length === 0"));
    assert.equal(await js("document.querySelector('#plugins').dataset.timers"), '0');
    assert.deepEqual(JSON.parse(fs.readFileSync(file)), saved, 'revocation preserves placement without writing');
    await plugins.enable('test.workspace', true);
    await until(() => js("document.querySelectorAll('[data-plugin-panel]').length === 2"));
    const loaded = new Promise(resolve => window.webContents.once('did-finish-load', resolve)); window.webContents.reload(); await loaded;
    await until(() => js("document.querySelectorAll('[data-plugin-panel]').length === 2"));
    assert.deepEqual(JSON.parse(fs.readFileSync(file)), saved);
    await js("(()=>{const select=[...document.querySelectorAll('#workspace .area-toolbar select')].at(-1);select.value='video';select.dispatchEvent(new Event('change'));})()");
    await until(() => js("!!document.querySelector('.workspace-area:last-child #screen')"));
    await js(`(()=>{const select=document.querySelector('#workspace .area-toolbar select');select.value=${JSON.stringify(panel)};select.dispatchEvent(new Event('change'));})()`);
    await until(() => js("document.querySelectorAll('[data-plugin-panel]').length === 2"));
    const frames = await js('window.stats().frames');
    await until(async () => await js('window.stats().frames') > frames + 3);
    const artifact = path.resolve('artifacts/workspace.png'); fs.mkdirSync(path.dirname(artifact), { recursive: true }); fs.writeFileSync(artifact, (await window.webContents.capturePage()).toPNG());
    console.log('WORKSPACE_PASS: video-only default, Cmd+, settings, split regions, multiple instances, divider/window drag and resize, overlay passthrough, popup hotkey, persistence, scoped cleanup, video relocation and reload identity');
    app.quit();
  } catch (error) { console.error(error); app.exit(1); }
});
