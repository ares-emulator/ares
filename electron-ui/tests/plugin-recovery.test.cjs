const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')

test('recovery reads metadata without compiling enabled plugins, preserves selections, and blocks activation until restart', async () => {
  const { PluginRegistry } = await import('../dist/plugins/registry.js')
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'ares-recovery-'))
  const data = path.join(temporary, 'profile'), source = path.join(temporary, 'broken')
  await fs.mkdir(data); await fs.mkdir(source)
  await fs.writeFile(path.join(source, 'manifest.json'), JSON.stringify({ id: 'test.broken', name: 'Broken build', version: '1.0.0', apiVersion: 1, entry: 'dist/plugin.js', build: { entry: 'missing.ts' }, capabilities: [], contributes: {} }))
  const config = JSON.stringify({ directories: [source], enabled: ['test.broken', 'test.missing'] })
  await fs.writeFile(path.join(data, 'enabled.json'), config)
  const registry = new PluginRegistry(path.join(temporary, 'no-bundled'), data, { request: async () => { throw new Error('No plugin service calls are allowed') } }, () => ({ session: 'safe', epoch: 1 }))
  try {
    const initial = await registry.initialize([], ['test.default'], true)
    assert.equal(initial.startupDisabled, true)
    assert.equal(initial.plugins[0].state, 'disabled')
    assert.equal(initial.plugins[0].configuredEnabled, true)
    assert.equal(initial.plugins[0].artifact, undefined, 'missing TS entry was never built')
    assert.equal(await fs.readFile(path.join(data, 'enabled.json'), 'utf8'), config)
    assert.equal(registry.attach().plugins[0].lease, undefined)
    await assert.rejects(registry.enable('test.broken', true), /plugins_disabled_until_restart/)
    await assert.rejects(registry.reload('test.broken'), /plugins_disabled_until_restart/)
    await assert.rejects(registry.add(source), /plugins_disabled_until_restart/)
    await registry.enable('test.missing', false)
    await registry.enable('test.broken', false)
    assert.deepEqual(JSON.parse(await fs.readFile(path.join(data, 'enabled.json'))).enabled, [])
    await assert.rejects(fs.stat(path.join(data, 'artifacts')), { code: 'ENOENT' })
  } finally { await registry.close(); await fs.rm(temporary, { recursive: true, force: true }) }
})

test('recovery preserves malformed configuration until explicit reset and retains plugin storage', async () => {
  const { PluginRegistry } = await import('../dist/plugins/registry.js')
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'ares-recovery-reset-'))
  const file = path.join(temporary, 'enabled.json')
  await fs.writeFile(file, '{broken')
  await fs.mkdir(path.join(temporary, 'storage'))
  await fs.writeFile(path.join(temporary, 'storage', 'keep.json'), '"preserved"')
  const registry = new PluginRegistry(path.join(temporary, 'none'), temporary, {}, () => undefined)
  try {
    const catalog = await registry.initialize([], [], true)
    assert.match(catalog.plugins[0].error, /JSON/)
    assert.equal(await fs.readFile(file, 'utf8'), '{broken')
    await registry.resetStartup()
    assert.deepEqual(JSON.parse(await fs.readFile(file)), { directories: [], enabled: [] })
    assert.equal(await fs.readFile(path.join(temporary, 'storage', 'keep.json'), 'utf8'), '"preserved"')
    assert.equal(registry.catalog().startupDisabled, true)
  } finally { await registry.close(); await fs.rm(temporary, { recursive: true, force: true }) }
})
