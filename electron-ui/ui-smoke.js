// Run with dev-browser --connect http://127.0.0.1:9237 run electron-ui/ui-smoke.js
const tabs = await browser.listPages();
const target = tabs.find(tab => tab.url.includes('/electron-ui/index.html'));
if (!target) throw new Error('Electron frontend tab not found');
const page = await browser.getPage(target.id);
console.log(await page.snapshotForAI());
await page.getByRole('button', { name: 'Pause', exact: true }).click();
await page.waitForTimeout(100);
const before = await page.evaluate(() => stats());
await page.waitForTimeout(300);
const after = await page.evaluate(() => stats());
if (after.frames !== before.frames) throw new Error('Pause did not stop frames');
await page.getByRole('button', { name: 'Resume', exact: true }).click();
await page.waitForTimeout(200);
if ((await page.evaluate(() => stats())).frames <= after.frames) throw new Error('Resume did not restart frames');
await page.getByRole('combobox', { name: 'Theme', exact: true }).selectOption('paper');
await page.getByRole('combobox', { name: 'Scaling', exact: true }).selectOption('integer');
await page.getByRole('checkbox', { name: 'Scanlines', exact: true }).check();
await page.getByRole('checkbox', { name: 'Panel on left', exact: true }).check();
await page.getByRole('button', { name: 'Block UI for 250 ms', exact: true }).click();
await page.waitForTimeout(300);
await page.locator('canvas').click();
await page.keyboard.down('x');
await page.waitForTimeout(200);
await page.keyboard.up('x');
await page.waitForTimeout(200);
console.log(await page.snapshotForAI());
console.log(await saveScreenshot(await page.screenshot(), 'ares-electron-customized.png'));
const result = await page.evaluate(() => stats());
if (result.maxPending !== 1 || result.glError !== 0) throw new Error('Frame/WebGL invariant failed');
console.log('UI_SMOKE_PASS', result);
console.log(await writeFile('ares-electron-ui-smoke.json', JSON.stringify(result, null, 2)));
// Restore the initial presentation after testing.
await page.getByRole('combobox', { name: 'Theme', exact: true }).selectOption('dark');
await page.getByRole('combobox', { name: 'Scaling', exact: true }).selectOption('fit');
await page.getByRole('checkbox', { name: 'Scanlines', exact: true }).uncheck();
await page.getByRole('checkbox', { name: 'Panel on left', exact: true }).uncheck();
